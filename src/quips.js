const used = new Map();
function pick(key, arr) {
  const i = used.get(key) || 0;
  used.set(key, i + 1);
  return arr[i % arr.length];
}

// 건물(short 이름 · 스타일)에 맞는 멘트 하나
export function quipFor(name, style) {
  const nm = name || '';
  if (nm) for (let i = 0; i < QUIPS.length; i++) if (QUIPS[i][0].test(nm)) return pick('r' + i, QUIPS[i][1]);
  const g = QUIPS_GENERIC[style] || QUIPS_GENERIC.any;
  return pick('g' + (style || 'any'), g.concat(QUIPS_GENERIC.any));
}
export function quipForObject(name) {
  for (const k of Object.keys(QUIPS_OBJ)) if (name.includes(k)) return pick('o' + k, QUIPS_OBJ[k]);
  return pick('oany', QUIPS_GENERIC.any);
}
